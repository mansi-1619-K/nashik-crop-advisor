import type {
  AiEvalSummary,
  EngineEvalSummary,
  RetrievalEvalSummary,
  StabilityResult,
} from "./types";

export interface ReportInput {
  generatedAt: string;
  engine: EngineEvalSummary;
  retrieval: RetrievalEvalSummary;
  stability: StabilityResult[];
  ai: AiEvalSummary | null;
}

const NOT_MEASURED = "**NOT MEASURED** (no GEMINI_API_KEY configured for this run)";

export function renderEvaluationReport(input: ReportInput): string {
  const { engine, retrieval, stability, ai } = input;

  const stabilityPrimaryPersistence =
    stability.length === 0
      ? null
      : Number((stability.filter((s) => s.primaryPersisted).length / stability.length).toFixed(4));
  const stabilityMeanOverlap =
    stability.length === 0
      ? null
      : Number((stability.reduce((sum, s) => sum + s.top3OverlapRatio, 0) / stability.length).toFixed(4));

  const failedScenarios = engine.perScenario.filter((s) => s.failures.length > 0);

  return `# Engine Evaluation Report

Generated by \`npm run evaluate\` at ${input.generatedAt}. Every number below is
computed from the run recorded here — nothing is transcribed from earlier runs or
estimated. Metrics that were not measured in this run appear as **NOT MEASURED**.

## Scope & provenance

- Scenarios: ${engine.scenarioCount} desk-defined cases (\`evaluation/scenarios/nashik-core-scenarios.json\`, quality: assumed)
- Retrieval labels: ${retrieval.queryCount} desk-labelled queries (\`evaluation/benchmarks/retrieval-labels.json\`, quality: assumed)
- Deterministic engine under test: \`lib/agriculture\` as committed; no live weather attached

## Constraint behaviour

| Metric | Value | Denomination |
| --- | --- | --- |
| Constraint-violation rate (${engine.perScenario.length} scenarios) | ${engine.constraintViolationRate} | share of mustBeExcluded expectations upheld |
| Expectation failures | ${engine.expectationFailures} of ${engine.totalExpectations} claimed expectations |

## Ranking accuracy

| Metric | Value | Basis |
| --- | --- | --- |
| Primary accuracy | ${engine.primaryAccuracyMeasured} | ${engine.primaryAccuracyNumerator}/${engine.primaryAccuracyDenominator} scenarios with a declared expected primary |

## Latency (in-process, deterministic path)

| p50 (ms) | p95 (ms) |
| --- | --- |
| ${engine.latencyMsP50} | ${engine.latencyMsP95} |

## Ranking stability under perturbation

${stability.length} perturbations (water ±1 level, soil textural neighbour) over scenarios with a declared primary.

| Metric | Value |
| --- | --- |
| Primary persisted after perturbation | ${stabilityPrimaryPersistence ?? "**NOT MEASURED**"} |
| Mean top-3 overlap ratio | ${stabilityMeanOverlap ?? "**NOT MEASURED**"} |

## Retrieval quality (lexical RAG)

| Metric | Value |
| --- | --- |
| Precision@3 | ${retrieval.precisionAt3} |
| Recall@3 | ${retrieval.recallAt3} |
| MRR | ${retrieval.mrr} |

${retrieval.misses.length > 0 ? `Queries with zero relevant hits:\n${retrieval.misses.map((m) => `- "${m.query}" → retrieved [${m.retrieved.join(", ") || "none"}], wanted ${m.relevant.join(", ")}`).join("\n")}` : "All labelled queries retrieved at least one relevant document."}

## AI narration layer (live Gemini)

${
  ai && ai.configured && ai.callCount > 0
    ? `Measured with ${ai.callCount} real calls (model \`${ai.model}\`):

| Metric | Value |
| --- | --- |
| AI-generated (vs static fallback) | ${ai.aiGeneratedCount}/${ai.callCount} (fallback rate ${ai.fallbackRate}) |
| First-attempt schema validity | ${ai.firstAttemptValidityRate} |
| Mean attempts per call | ${ai.meanAttempts} |
| Latency p50 / p95 (ms) | ${ai.latencyMsP50} / ${ai.latencyMsP95} |
| Calls emitting citations | ${ai.citationEmissionRate} |
| Calls with hallucinated citation ids dropped | ${ai.hallucinatedCitationCalls} |`
    : ai?.note
      ? `${NOT_MEASURED} — ${ai.note}`
      : NOT_MEASURED
}

## Failed expectations

${failedScenarios.length === 0 ? "None. All scenario expectations held in this run." : failedScenarios.map((s) => `- **${s.id}**: ${s.failures.join("; ")}`).join("\n")}

## Interpretation rules

1. These numbers describe THIS commit's code against THESE fixtures — they are
   not transferable claims about agronomy or about future versions.
2. Fixtures carry \`quality: assumed\`: expert-defined desk judgements validating
   internal consistency and documented engine behaviour.
3. Any metric marked **NOT MEASURED** must not be quoted anywhere as a value.
`;
}
